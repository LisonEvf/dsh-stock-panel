/** 竞价时段的一行竞价特征（由 `.mcp__local__auction` 逐票算出，与竞价雷达同口径）。 */
export interface WarAuctionRow {
  symbol: string
  name: string
  /** 竞价末端价 vs 昨收（%）。 */
  openPct: number
  climaxDir: 'buy' | 'sell' | 'none'
  nearLimit: boolean
  fakeBigThenDrop: boolean
  /** 昨日预期状态（该票在预期清单里时）。 */
  expectState?: ExpectItem['state']
  /** 系统初判（`judgeExpectation`，与竞价雷达同一函数）。 */
  autoVerdict?: Verdict
}

/**
 * 一次作战思路的**全部素材**（每一项都对应一个已有页面的产出；缺失就是缺失，不补空）。
 *
 * 为什么用具体类型而不是 `unknown`：组装层是"其他板块 → 作战板块"的唯一接口，
 * 类型写死才能让"某个页面改了字段名"在编译期就炸，而不是模型悄悄少看一块。
 */
export interface WarMaterials {
  day: string
  stage: Stage
  phase: SessionPhase
  /** 当前时刻 HH:MM。 */
  clockText: string
  /** 盘中窗口说明（验证窗 / 主段 / 尾盘）。 */
  windowNote: string
  breadth: Breadth | null
  regime: Regime | null
  situation: Situation | null
  ladder: LadderSnapshot | null
  events: EventItem[]
  pulses: BoardPulse[]
  /** 可采信的自挖类（已过弱链/传递链筛选，按强度降序）。null = 引擎没取到。 */
  concepts: ConceptClassRow[] | null
  /** 自挖板块素材的说明（as_of / 可用类数 / 排除了几个）。 */
  conceptsNote: string
  /** 池内却孤立的强势票（"独狼"，自挖板块页也会列出来）。 */
  isolatedTop: Array<{ symbol: string; name: string; chgPct: number | null; limitUp: boolean }>
  /** 选股筛选（预设「放量上攻」）命中：涨停梯队之外那批"没封板但在放量"的票。 */
  screened: AShareRow[]
  positions: Position[]
  watchlist: WatchItem[]
  /** 最近一份复盘存档的预期清单（"用户原来想打什么"，作为输入之一而不是答案）。 */
  myPlan: { day: string; expectations: ExpectItem[]; mainLine: string[]; riskNote: string } | null
  /** 竞价特征（仅竞价/盘前时段非空）。 */
  auctions: WarAuctionRow[]
  /** 素材缺口说明（"自挖板块引擎不可用"…）—— 进 prompt，也进界面。 */
  missing: string[]
}

/** 素材条数上限（体量纪律：`AI_CONTEXT_MAX_BYTES` = 24KB，这里留足余量）。 */
export const MATERIAL_CAPS = {
  boards: 15,
  concepts: 8,
  conceptMembers: 10,
  ladder: 20,
  events: 15,
  pulses: 8,
  positions: 8,
  watchlist: 15,
  expectations: 5,
  isolated: 8,
  auction: 8,
  screener: 8,
} as const

/** 保留两位（模型不需要 8 位小数；也省 token）。 */
function r2(v: unknown): number | null {
  const n = typeof v === 'number' ? v : Number(v)
  if (!Number.isFinite(n)) return null
  return Math.round(n * 100) / 100
}

/** 符号（market+code → 标准符号）。 */
function sym(market: string, code: string): string {
  return `${market.toUpperCase()}${code}`
}

/**
 * 组装喂给模型的上下文（**纯函数**：同样的素材 → 同样的上下文，便于单测与追溯）。
 *
 * `sectorUniverse` 是护栏的"允许方向名"白名单，必须由组装方显式声明：
 * 现在它 = 行情页板块榜名（涨停家数排序的官方板块名）。**自挖类没有名字**
 * 是刻意的 —— 给类起名是「自挖板块」页的模型调用，作战页不该偷偷再花一次预算；
 * 类的作用是把"哪一批票在共动"作为**证据**（成员表）交给模型。
 */
export function buildWarContext(m: WarMaterials): Record<string, unknown> {
  const boards = (m.ladder?.boards ?? []).slice(0, MATERIAL_CAPS.boards)
  const sectorUniverse = boards.map((b) => b.name).filter((n) => n !== '')

  const boardsOut = boards.map((b: BoardStat) => ({
    name: b.name,
    limitUpCount: b.limitUpCount,
    pct: r2(b.pct),
    rep: b.rep,
    repSymbol: b.repCode === '' ? null : sym(b.rep === '' ? 'SH' : boardMarketOf(b), b.repCode),
  }))

  const conceptsOut = (m.concepts ?? []).slice(0, MATERIAL_CAPS.concepts).map((c) => ({
    id: c.classId,
    size: c.size,
    strength: r2(c.strength),
    chgMean: r2(c.chgMean),
    limitUpN: c.limitUpN,
    intraCorr: r2(c.intraCorr),
    strongDensity: r2(c.strongDensity),
    members: c.members.slice(0, MATERIAL_CAPS.conceptMembers).map((mem) => ({
      symbol: sym(mem.market, mem.code),
      name: mem.name,
      pct: r2(mem.chgPct),
      limitUp: mem.limitUp,
    })),
  }))

  return {
    day: m.day,
    stage: m.stage,
    phase: m.phase,
    clock: m.clockText,
    window: m.windowNote,
    /** 方向名白名单（护栏按它逐字反查 `sectors[].name`）。 */
    sectorUniverse,
    market: {
      breadth: m.breadth === null ? null : {
        up: m.breadth.up,
        down: m.breadth.down,
        flat: m.breadth.flat,
        limitUp: m.breadth.limitUp,
        limitDown: m.breadth.limitDown,
        strongUp: m.breadth.strongUp,
        strongDown: m.breadth.strongDown,
        amountYi: r2(m.breadth.amountSum / 1e8),
        avgPct: r2(m.breadth.avgPct),
      },
      regime: m.regime === null ? null : {
        temperature: m.regime.temperature,
        band: m.regime.band,
        drivers: m.regime.drivers,
      },
      situation: m.situation,
      limitDownCount: m.ladder?.limitDownCount ?? null,
    },
    boards: boardsOut,
    concepts: conceptsOut,
    conceptsNote: m.conceptsNote,
    isolated: m.isolatedTop.slice(0, MATERIAL_CAPS.isolated).map((s) => ({
      symbol: s.symbol,
      name: s.name,
      pct: r2(s.chgPct),
      limitUp: s.limitUp,
    })),
    /**
     * 选股筛选（预设「放量上攻」）的命中。
     *
     * 为什么单列一块而不是并进 ladder：ladder 是"已经封板"的票，这一块是"在放量但没封板"
     * 的票 —— 后者的信息量恰好在于"还没走完"，也正好是选股筛选页的口径
     * （`lib/screener` 的同一份预设，零额外请求：全 A 快照本来就在手上）。
     */
    screened: m.screened.slice(0, MATERIAL_CAPS.screener).map((r) => ({
      symbol: sym(r.market, r.code),
      name: r.name,
      pct: r2(r.pct),
      volRatio: r2(r.vol_ratio),
      turnover: r2(r.turnover),
      amountYi: r2((r.amount ?? 0) / 1e8),
    })),
    ladder: (m.ladder?.limitUp ?? []).slice(0, MATERIAL_CAPS.ladder).map((s) => ({
      symbol: sym(s.market, s.code),
      name: s.name,
      streak: s.streak,
      pct: r2(s.pct),
      amountYi: r2((s.amount ?? 0) / 1e8),
    })),
    events: m.events.slice(0, MATERIAL_CAPS.events).map((e: EventItem) => ({
      kind: e.kind,
      name: e.name,
      symbol: sym(e.market, e.code),
      time: e.time,
      desc: e.desc,
    })),
    pulses: m.pulses.slice(0, MATERIAL_CAPS.pulses).map((p: BoardPulse) => ({
      name: p.name,
      deltaLimitUp: p.deltaLimitUp,
      limitUp: p.limitUp,
      leader: p.leader?.name ?? null,
    })),
    positions: m.positions.slice(0, MATERIAL_CAPS.positions).map((p: Position) => ({
      symbol: p.symbol,
      name: p.name,
      entryPrice: r2(p.entryPrice),
      shares: p.shares,
      entryDate: p.entryDate,
      stopLoss: r2(p.plan.stopLoss),
      failIf: p.plan.failIf,
      expectState: p.expectState ?? null,
    })),
    watchlist: m.watchlist.slice(0, MATERIAL_CAPS.watchlist).map((w: WatchItem) => ({
      symbol: sym(w.market, w.code),
      name: w.name,
    })),
    myPlan: m.myPlan === null ? null : {
      day: m.myPlan.day,
      mainLine: m.myPlan.mainLine,
      riskNote: m.myPlan.riskNote,
      items: m.myPlan.expectations.slice(0, MATERIAL_CAPS.expectations).map((e: ExpectItem) => ({
        symbol: e.symbol,
        name: e.name,
        state: e.state,
        scenario: e.scenario,
        auctionOK: e.auctionOK,
        failIf: e.failIf,
        reason: e.reason,
      })),
    },
    auction: m.auctions.slice(0, MATERIAL_CAPS.auction).map((a) => ({
      symbol: a.symbol,
      name: a.name,
      openPct: r2(a.openPct),
      climaxDir: a.climaxDir,
      nearLimit: a.nearLimit,
      fakeBigThenDrop: a.fakeBigThenDrop,
      expectState: a.expectState ?? null,
      autoVerdict: a.autoVerdict ?? null,
    })),
    /** 素材缺口：让模型知道"自己少看了什么"，也让界面能解释"为什么它只说证据不足"。 */
    missing: m.missing,
  }
}

/**
 * 板块代表股的交易所前缀。
 *
 * `BoardStat` 只给了代表股**代码**（不带市场），而模型的符号必须是标准符号。
 * 按代码段推断（6/9 → SH，4/8 → BJ，其余 → SZ），与 `lib/ai-contract` 的
 * `normalizeSymbol` 同一口径 —— 这里显式写出来是为了让"推断"这件事可见。
 */
function boardMarketOf(b: BoardStat): string {
  const head = b.repCode.charAt(0)
  return head === '6' || head === '9' ? 'SH' : head === '4' || head === '8' ? 'BJ' : 'SZ'
}

/** 自挖板块素材的精简（筛选 + 排序 + 说明），供页面与上下文共用。 */
export function prepareConcepts(
  payload: { ok: boolean; asOf: string; classes: ConceptClassRow[]; notes: string[]; params?: { minCorr: number } } | null,
): { rows: ConceptClassRow[]; note: string } {
  if (payload === null || !payload.ok) {
    return { rows: [], note: `自挖板块引擎不可用：${payload?.notes.join('；') ?? '未取数'}` }
  }
  const minCorr = payload.params?.minCorr ?? NAMING_PARAMS_FALLBACK.minCorr
  const { usable, dropped } = filterUsableClasses(payload.classes, minCorr)
  const rows = [...usable].sort(compareByStrength).slice(0, MATERIAL_CAPS.concepts)
  return {
    rows,
    note:
      `as_of ${payload.asOf || '—'} · window ${NAMING_PARAMS_FALLBACK.window} / min_corr ${minCorr} / pool ${NAMING_PARAMS_FALLBACK.poolN}`
      + ` · 可用 ${usable.length} 类（用了前 ${rows.length}）· 排除 ${dropped.length} 个弱链/传递链可疑类`,
  }
}

/**
 * 符号 → 名称。
 *
 * 模型只给标准符号（护栏按符号查白名单），但界面上"SH600519"远不如"贵州茅台"可读 ——
 * 名称一律**从素材回查**（而不是让模型自己填，那样它就能编名字了）。
 * 查不到就显示符号本身（诚实：这个名字今天确实没出现在任何一块素材里）。
 */
export function nameIndexOf(m: WarMaterials): Map<string, string> {
  const map = new Map<string, string>()
  const put = (s: string, n: string): void => {
    if (s !== '' && n !== '' && !map.has(s)) map.set(s, n)
  }
  for (const p of m.positions) put(p.symbol, p.name)
  for (const w of m.watchlist) put(sym(w.market, w.code), w.name)
  for (const e of m.myPlan?.expectations ?? []) put(e.symbol, e.name)
  for (const s of m.ladder?.limitUp ?? []) put(sym(s.market, s.code), s.name)
  for (const c of m.concepts ?? []) for (const mem of c.members) put(sym(mem.market, mem.code), mem.name)
  for (const a of m.auctions) put(a.symbol, a.name)
  for (const s of m.isolatedTop) put(s.symbol, s.name)
  for (const r of m.screened) put(sym(r.market, r.code), r.name)
  for (const b of m.ladder?.boards ?? []) if (b.repCode !== '') put(sym(boardMarketOf(b), b.repCode), b.rep)
  return map
}

