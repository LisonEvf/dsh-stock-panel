/** 一份作战思路的存档（含"模型看到的是哪份素材"的元信息）。 */
export interface WarPlanRecord {
  day: string
  stage: Stage
  at: number
  plan: WarPlan
  /** 模型原文（结构化失败时的兜底，也是留痕）。 */
  raw: string
  provider: string
  model: string
  ms: number
  ctxBytes: number
  /** 自愈裁剪记录（有值 = 模型少看了东西，界面必须显示）。 */
  shrunk: string[]
  /** 白名单规模：模型这次能点名的票 / 能用的方向名（来自 host 半的护栏报告）。 */
  pool: { symbols: number; sectors: number }
  /** 素材缺口。 */
  missing: string[]
  /** 思路"属于哪个时段"的可读标签（竞价/盘中/尾盘/复盘）。 */
  stageLabel: string
  /**
   * 生成时**写进当日记录**的内容（"模型结论被采纳了多少"的留痕）。
   *
   * 为什么存在记录里而不是组件 state：刷新页面后这条痕迹必须还在 ——
   * 否则用户第二天回看"当时的三问是谁答的"就只能靠猜（`from: 'ai'` 只标了来源，
   * 没标这一轮补了哪几项）。
   */
  adopted: AdoptionResult
}

/** 同一时段内的思路多久算"新鲜"（过期只标记、不自动重算 —— 重算由用户决定）。 */
export const WAR_PLAN_TTL_MS = 30 * 60 * 1000

const STORAGE_KEY = 'dsh-stock-panel:war-plan:v1'
const MAX_RECORDS = 40

/** 记录键：一天里的每个时段各一份（竞价/盘中/尾盘/复盘各一次模型调用，不重复烧）。 */
export function planKey(day: string, stage: Stage): string {
  return `${day}:${stage}`
}

let records: Record<string, WarPlanRecord> = load()
const listeners = new Set<() => void>()

function load(): Record<string, WarPlanRecord> {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (raw === null) return {}
    const parsed = JSON.parse(raw) as unknown
    if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) return {}
    const out: Record<string, WarPlanRecord> = {}
    for (const [k, v] of Object.entries(parsed as Record<string, unknown>)) {
      if (v === null || typeof v !== 'object') continue
      const rec = v as WarPlanRecord
      if (typeof rec.day !== 'string' || typeof rec.at !== 'number' || rec.plan === undefined) continue
      out[k] = rec
    }
    return out
  } catch {
    return {}
  }
}

function persist(): void {
  try {
    const entries = Object.entries(records).sort((a, b) => b[1].at - a[1].at)
    records = Object.fromEntries(entries.slice(0, MAX_RECORDS))
    localStorage.setItem(STORAGE_KEY, JSON.stringify(records))
  } catch {
    /* 隐私模式/配额：忽略 */
  }
  // A1：host 域同步（键值表 → shape: 'keyed'）。
  syncTable('war_plans', records)
}

function notify(): void {
  for (const fn of listeners) {
    try {
      fn()
    } catch {
      /* ignore */
    }
  }
}

// A1：host 域数据落地后，用权威版本重载并通知 UI。
onHostHydrated(() => {
  records = load()
  notify()
})

/** 订阅思路存档变更（跨组件同步）。 */
export function subscribeWarPlan(fn: () => void): () => void {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

/** 某日某时段的思路（无则 null）。 */
export function getWarPlan(day: string, stage: Stage): WarPlanRecord | null {
  return records[planKey(day, stage)] ?? null
}

/** 写入/覆盖一份思路存档。 */
export function saveWarPlan(rec: WarPlanRecord): void {
  records = { ...records, [planKey(rec.day, rec.stage)]: rec }
  persist()
  notify()
}

/** 丢掉某日某时段的思路（用户点「重算」前的清理，或想强制刷新）。 */
export function clearWarPlan(day: string, stage: Stage): void {
  const key = planKey(day, stage)
  if (!(key in records)) return
  const next = { ...records }
  delete next[key]
  records = next
  persist()
  notify()
}

/** 新鲜度（过期只是标注，不自动重算）。 */
export function planFreshness(rec: WarPlanRecord, now: number): 'fresh' | 'stale' {
  return now - rec.at <= WAR_PLAN_TTL_MS ? 'fresh' : 'stale'
}

/** HH:MM。 */
function hhmm(ts: number): string {
  const d = new Date(ts)
  return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`
}

/**
 * 回包结构不可用时的占位思路。
 *
 * 为什么要有它而不是"直接报错、什么都不存"：模型**确实说了话**（原文在 `raw` 里），
 * 「说了但结构不对」必须留痕并显示，否则用户看到的是"点了一下什么都没发生"。
 * 这条占位思路是 `insufficient`（不写任何当日记录），原因写明"回包不可用"。
 */
export function unusableWarPlan(reason: string): WarPlan {
  return {
    insufficient: true,
    reason,
    summary: '',
    stance: 'wait',
    sectors: [],
    picks: [],
    q1: null,
    q2: null,
    actions: [],
    verdicts: [],
    avoid: [],
    evidence: [],
    guard: { droppedSymbols: [], droppedSectors: [], ungrounded: [], grounded: 0, symbolPool: 0, sectorPool: 0 },
  }
}

// ────────────────────────────── 采纳（模型结论 → 当日记录） ──────────────────────────────

/** 采纳结果（哪些写进去了、哪些因为"你已经有答案"而保留原样）。 */
export interface AdoptionResult {
  /** 写进当日记录的项（人读文案）。 */
  written: string[]
  /** 保留原答案的项（人读文案）—— **绝不覆盖人工答案**。 */
  kept: string[]
}

/**
 * 把模型的三问落点 / 持仓动作 / 竞价判定**按默认值**写进当日运行记录。
 *
 * 语义（这是"模型给默认结论、用户可改可驳回"的落点）：
 *   · 只填**空位**：用户已经答过的（人工或更早的采纳）一律不动 —— 每次重新生成思路
 *     都只是"补齐没答的"，不会把人的判断反复覆盖掉；
 *   · 只写**素材里有的**持仓与预期（护栏在 host 半保证票在素材内；这里再按持仓台账
 *     与预期清单的事实过滤一次：思路可能基于几轮前的素材）；
 *   · 全部标记 `from: 'ai'`，Q 卡上显示「模型→」，人一点就变回人工。
 *
 * 副作用明确（写 dayrun），所以单独成函数、由组件在**生成成功后**调用一次。
 */
export function adoptWarPlan(day: string, plan: WarPlan, positions: Position[]): AdoptionResult {
  const written: string[] = []
  const kept: string[] = []
  if (plan.insufficient) return { written, kept }

  // 一次性读当日记录：每写一项都要重读（setXxx 会 upsert），但"是否已答"按最初始的快照判
  const before = getDayRun(day)
  if (plan.q1 !== null) {
    if (before?.q1 === undefined) {
      setQ1(day, plan.q1.value, 'ai')
      written.push(`Q1 ${q1Label(plan.q1.value)}`)
    } else {
      kept.push('Q1（已有人工答案，保留）')
    }
  }
  if (plan.q2 !== null) {
    if (before?.q2 === undefined) {
      setQ2(day, plan.q2.value, 'ai')
      written.push(`Q2 ${situationShortLabel(plan.q2.value)}`)
    } else {
      kept.push('Q2（已有人工答案，保留）')
    }
  }

  const held = new Set(positions.map((p) => p.symbol))
  for (const a of plan.actions) {
    // 只覆盖**当前持仓**：思路可能基于几轮前的素材，已清掉的票不该再写动作
    if (!held.has(a.symbol)) {
      kept.push(`${a.symbol} 动作（已不在持仓台账）`)
      continue
    }
    if (before?.q3?.bySymbol[a.symbol] !== undefined) {
      kept.push(`${a.symbol} 动作（已有人工答案，保留）`)
      continue
    }
    setQ3Symbol(day, a.symbol, a.action, 'ai')
    written.push(`${a.symbol} ${q3Label(a.action)}`)
  }
  // 空仓且模型也没给持仓动作 → 打「空仓观望」钩（无动作也是一种决策）
  if (positions.length === 0 && plan.actions.length === 0 && before?.q3?.idle !== true) {
    setQ3Idle(day, true)
    written.push('Q3 空仓观望')
  }

  // 竞价判定只对**预期清单里的票**有意义（清单外没有对照基准，判定不可证伪）
  const expectSymbols = latestExpectationSymbols()
  for (const v of plan.verdicts) {
    if (expectSymbols !== null && !expectSymbols.includes(v.symbol)) {
      kept.push(`${v.symbol} 判定（不在预期清单，保留未判）`)
      continue
    }
    if (before?.verdicts[v.symbol] !== undefined) {
      kept.push(`${v.symbol} 判定（已有人工答案，保留）`)
      continue
    }
    setVerdict(day, v.symbol, v.verdict, 'ai')
    written.push(`${v.symbol} ${v.verdict}`)
  }

  // 保证"这一天有记录"（即使三问都没落点，也要留下当天有思路的痕迹）
  ensureDayRun(day)
  return { written, kept }
}

/**
 * 最近一份复盘的预期清单符号（判定只对清单内的票有意义：清单外没有对照基准）。
 *
 * ⚠️ 这是本模块**唯一**的界面侧依赖（`review-store`），且本模块**只被 client 半引用**
 * （host 半只引 `ai-contract` + `war-plan-guard`）—— 别把 `war-plan.ts` 拖进 host 链路。
 * 读不到（存档为空/异常）返回 null = 不过滤，而不是把整批判定静默丢掉。
 */
function latestExpectationSymbols(): string[] | null {
  try {
    const plan = getLatestPlan(today())
    if (plan === null) return null
    return plan.expectations.map((e) => e.symbol)
  } catch {
    return null
  }
}

function q1Label(v: string): string {
  return v === 'strengthen' ? '增强' : v === 'weaken' ? '衰减' : '中性'
}

function q3Label(v: string): string {
  return v === 'hold' ? '持有' : v === 'reduce' ? '减仓' : v === 'clear' ? '清仓' : '半仓试错'
}
