/** 自动生成的判定结果（`why` 会显示在卡片上：让"为什么没自动跑"看得见）。 */
export interface AutoDecision {
  run: boolean
  why: string
}

/**
 * 该不该为当前时段自动生成一次作战思路（页面打开 / 时段切换各判一次）。
 *
 * 三条规则，全部来自既有纪律：
 *   1. **同一时段已有缓存** → 不跑（这是"打开页面就烧一次模型"的唯一刹车）；
 *   2. **没有盘面素材**（休市 / 取数失败 / 数据源不可达）→ 不跑；
 *      自动跑只会得到一句"证据不足"，白花一次调用（休市期不发起全量请求的同一立场）；
 *   3. 其余（竞价 / 盘中 / 尾盘，且素材在手）→ 跑一次。
 */
export function autoGenerateDecision(input: {
  hasMaterials: boolean
  existing: WarPlanRecord | null
  now: number
}): AutoDecision {
  if (input.existing !== null && planFreshness(input.existing, input.now) === 'fresh') {
    return { run: false, why: `已有时段内的思路（${hhmm(input.existing.at)} 生成，可重算）` }
  }
  if (!input.hasMaterials) {
    return { run: false, why: '没有可用的盘面素材（休市 / 取数失败）→ 不自动生成，省模型预算' }
  }
  return { run: true, why: '本时段第一次打开：自动生成一次' }
}

