/**
 * src/lib/war-plan.ts —— 「作战思路」的素材组装、时段缓存与采纳（v1.6 重做作战板块）。
 *
 * ## 这一版把「作战」页的产物换掉了什么
 *
 * 旧版作战页只**展示**数据，决策全交回用户：自己在复盘页写预期、自己在 Q1/Q2/Q3 卡上
 * 点选答案、自己逐条判竞价。新版反过来 —— **模型给作战思路**（主攻方向 / 候选票 /
 * 触发与失败条件 / 三问落点 / 持仓动作 / 竞价判定），用户只做采纳、修改或驳回。
 *
 * ## 「以其他板块为基础，不是空穴来风」在这里怎么落地
 *
 * 两层：
 *   1. **素材层（本文件）**：思路的输入**全部**取自其他页面的真实产出 ——
 *      行情页（广度/温度计/板块榜/涨停梯队）、自挖板块页（市场自聚类 + 强度分）、
 *      选股筛选页（全 A 快照，与行情页同源）、复盘页（存档的预期清单/主线/风险备注）、
 *      竞价雷达（竞价特征 + 系统初判）、事件流与板块脉冲、持仓台账与自选。
 *      **不给它别的东西，也绝不让它自己去取数** —— 模型看到的正是用户屏幕上那份；
 *   2. **护栏层（`lib/war-plan-guard.ts`）**：模型只能说素材里出现过的票与板块名，
 *      引文要能逐字/数字反查。越界的东西被剔除并**显示出来**。
 *
 * ## 成本纪律（与全仓同一条口径）
 *
 *   · **不新增任何轮询**：思路只在「页面打开 / 时段切换 / 用户点重算」时生成，
 *     按 `${day}:${stage}` 缓存（同一时段内重复打开 = 0 次模型调用，页头显示这件事）；
 *   · **非交易时段不自动生成**：休市期没有盘面素材，自动跑一次模型只会得到
 *     "证据不足"——那是一次白花的调用（`autoGenerateDecision` 把这条纪律写成了纯函数）；
 *   · 自挖板块素材走**已有的** `hist_concept_classes`（引擎快照，服务端缓存），
 *     不额外命名、不额外采集 —— 命名那一路的开销与缓存属于「自挖板块」页，这里不碰。
 */
